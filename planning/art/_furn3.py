    # 更精确：取最近/最远点
    nx=min(max(90,b[2]),b[4]); ny=min(max(30,b[3]),b[5])
    dmin=math.hypot(nx-90,ny-30); dmax=max(ds)
    if dmin<22.5 and dmax>21.5: err.append(('WALL',b[1],round(dmin,1),round(dmax,1)))
