def bx(t):
    r,n,cx,cy,w,d=t
    return (r,n,cx-w/2,cy-d/2,cx+w/2,cy+d/2)
def ov(a,b,e=0):
    return not (a[4]<=b[2]+e or b[4]<=a[2]+e or a[5]<=b[3]+e or b[5]<=a[3]+e)
