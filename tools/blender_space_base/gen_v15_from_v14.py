"""Generate tools/blender_space_base/build_scene_v15.py from the frozen v14 builder.

Implements planning/art/SPACE_BASE_CORE_ROOMS_ART_PLAN_20261108.md (v1.3) only:
the four core rooms are rebuilt, everything else is byte-identical to v14.

    python tools/blender_space_base/gen_v15_from_v14.py
"""
from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "build_scene_v14.py"
DST = HERE / "build_scene_v15.py"
ROOMS = HERE / "v15_rooms_src.py"

NEW_MATS = '''        # ---- v15 四核心区（复核 D2/D5/D9：冷相深色 + 色温预补偿）
        "h1_floor": make_mat("v15.h1_floor", "#767C78", 0.90),
        "h1_disc": make_mat("v15.h1_disc", "#222B2D", 0.86),
        "h2_poolbed": make_mat("v15.h2_poolbed", "#3D4444", 0.92),
        "h3_pitbed": make_mat("v15.h3_pitbed", "#2A4160", 0.86),
        "cap_h1": make_mat("v15.cap_h1", "#1C7C88", 0.62),
        "cap_h2": make_mat("v15.cap_h2", "#3E6E73", 0.62),
        "cap_h3": make_mat("v15.cap_h3", "#2C4A78", 0.66),
        "cap_h4": make_mat("v15.cap_h4", "#3E9159", 0.62),
'''

DRUM_OLD = """    # centrifuge drum inside H1
    cx, cy = av(-69.0, -22.0)
    add_cyl("h1_drum", cx, cy, z, z + 19.7, 8.75, m["wall"], c, vertices=40)
    add_cyl("h1_drum_band", cx, cy, z + 3.62, z + 3.98, 8.95, m["evac_blue"], c, vertices=40)
    add_cyl("h1_drum_cap", cx, cy, z + 19.7, z + 20.1, 8.2, m["steel"], c, vertices=40)
    add_cyl("h1_drum_eye", cx, cy, z + 20.1, z + 20.3, 3.2, m["dark"], c, vertices=24)
"""

CAP_OLD = '''            avr(f"{name.lower()}_up_{tag}", a0, a1, b0, b1, z + HALL_H, z + HALL_H + 0.18,
                m["cope"], c)'''
CAP_NEW = '''            avr(f"{name.lower()}_up_{tag}", a0, a1, b0, b1, z + HALL_H, z + HALL_H + 0.18,
                m.get("cap_%s" % name.lower(), m["cope"]), c)'''


def main() -> int:
    s = SRC.read_text(encoding="utf-8")

    # 1. new materials
    anchor = "        # ---- v13 水平试车间（露天防爆试验场）"
    if anchor not in s:
        raise SystemExit("GEN_NO_MAT_ANCHOR")
    s = s.replace(anchor, NEW_MATS + anchor, 1)

    # 2. per-hall wall cap colour (the facade colour carrier, plan 5.9)
    if CAP_OLD not in s:
        raise SystemExit("GEN_NO_CAP")
    s = s.replace(CAP_OLD, CAP_NEW, 1)

    # 2b. remove the v11 20 m placeholder drum that fills H1 (blocks the whole room)
    if DRUM_OLD not in s:
        raise SystemExit("GEN_NO_DRUM")
    s = s.replace(DRUM_OLD, "", 1)

    # 3. drop the CEO constant (user ruling 22:19 "no exec suite")
    ceo = "CEO = (100, 140, 45, 75, 12.0, 16.5)   # x0,x1,y0,y1,z0,z1\n"
    if ceo not in s:
        raise SystemExit("GEN_NO_CEO_CONST")
    s = s.replace(ceo, "", 1)
    s = s.replace('"rug": make_mat("v6.rug", "#C9B49A", 0.85),                # CEO 亮地毯（S14 对比）',
                  '"rug": make_mat("v6.rug", "#C9B49A", 0.85),                # v6 leftover (unused)')

    # 4. drop build_h1..build_h4 + build_ceo (dead code, 70 m grid, wrong heading)
    a = s.index("def build_h1(m):")
    b = s.index("\ndef strip_h_open(")
    s = s[:a] + s[b + 1:]

    # 5. replace fit_out with the v15 four-room build
    a = s.index("def fit_out(")
    b = s.index("\ndef build_core_v11(")
    rooms = ROOMS.read_text(encoding="utf-8").rstrip() + "\n"
    s = s[:a] + rooms + s[b + 1:]

    s = s.replace("Generated by gen_v14_from_v13.py", "Generated by gen_v15_from_v14.py", 1)
    s = s.replace('"""航天基地', '"""航天基地', 1)
    DST.write_text(s, encoding="utf-8")
    n = s.count("_v15_")
    print("GEN_V15_OK", DST.name, len(s), "chars, refs=", n)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
